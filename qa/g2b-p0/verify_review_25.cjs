'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const d=JSON.parse(fs.readFileSync('qa/g2b-p0/review-25.snapshot.json','utf8'));
const r=d.cases;
const eq=(a,b,label)=>assert.equal(a,b,label);
eq(d.schemaVersion,'G2B_P0_DIRECT_SOURCE_REVIEW_25_V1','schema');
eq(r.length,25,'25 review checks');
eq(new Set(r.map(x=>x.caseId)).size,25,'unique case IDs');
eq(new Set(r.map(x=>x.exerciseId)).size,24,'24 unique exercises');
eq(r.filter(x=>x.category==='G1_CORRECTION').length,10,'10 G1 corrections');
eq(r.filter(x=>x.category==='VISUAL_TOPOLOGY').length,15,'15 structural visuals');
eq(r.filter(x=>x.exerciseId==='SGK_B001_LT03_E04').length,2,'one cross-category overlap');
eq(d.metrics.originalG2B96Signatures,0,'96 G2B source signoffs pending');
for(const x of r){
 assert.ok(/^([CV])\d{2}$/.test(x.caseId),'case ID');
 assert.ok(/^(?:SGK|VBT)_B\d{3}_/.test(x.exerciseId),'source ID');
 assert.ok(/^MATH_B\d{3}$/.test(x.lessonId),'lesson ID');
 assert.ok(x.sourceTrack==='SGK'||x.sourceTrack==='VBT','source track');
 assert.ok(/^\d+(?:,\d+)?$/.test(x.printedPages),'printed pages');
 assert.ok(x.sourcePDFURL.startsWith('https://drive.google.com/file/d/'),'source PDF');
 eq(x.sourcePDFSHA256,d.PDFPins[x.sourceTrack],'source PDF SHA');
 assert.ok(/^[a-f0-9]{64}$/.test(x.excerptRGBSHA256)||/^92:[a-f0-9]{64};93:[a-f0-9]{64}$/.test(x.excerptRGBSHA256),'private pixel digest');
 assert.ok(/INDEX_ONLY/.test(x.skillIdIndexOnly),'no fake approved skill');
 assert.ok(x.sourceEvidenceStatement.length>=15,'evidence statement');
 eq(x.reviewerDecision,'NOT_SIGNED','independent signature absent');
 eq(x.reviewGate,'NOT_APPROVED','no automatic approval');
 eq(x.reviewerId,null,'no fabricated reviewer');
 eq(x.reviewedAt,null,'no fabricated time');
 eq(x.reviewerEvidenceSHA256,null,'no invented reviewer hash');
 eq(x.rendererGrant,'DENY','renderer gate');
 eq(x.assetGrant,'DENY','asset gate');
 eq(x.publicVariantGrant,'DENY','public variant gate');
 eq(x.partSlotCountTopology,'PENDING_INDEPENDENT','topology approval pending');
}
const critical=r.find(x=>x.caseId==='C10');
assert(critical&&critical.exerciseId==='SGK_B023_LT04_E04'&&critical.printedPages==='94');
assert(/32/.test(critical.sourceEvidenceStatement)&&/26/.test(critical.sourceEvidenceStatement));
const relation=r.find(x=>x.exerciseId==='SGK_B022_LT02_E05');
assert(relation&&/Mai/.test(relation.sourceEvidenceStatement)&&/Mi/.test(relation.sourceEvidenceStatement)&&relation.printedPages==='86');
const scan=JSON.stringify(d);
for(const secret of ['"answer":','"solutionPrompt":','"gradingKey":','"studentId":'])assert(!scan.includes(secret),'unexpected private result key');
console.log('G2B P0 REVIEW PREP PASS: 10 G1 corrections; 15 complex figures; 24 unique; 0 independent signoffs; 0 grants.');
