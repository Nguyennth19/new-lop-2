'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const p='qa/coverage75/DATA_B_COVERAGE75_SNAPSHOT.json';
const d=JSON.parse(fs.readFileSync(p,'utf8'));
const a=d.records;
const totals=(k)=>a.reduce((n,r)=>n+r.core[k],0);
const eq=(x,y,label)=>assert.equal(x,y,label);
eq(d.schemaVersion,'DATA_B_COVERAGE75_AUDIT_SNAPSHOT_V1','version');
eq(a.length,75,'75 entries');
eq(new Set(a.map(r=>r.lessonId)).size,75,'unique lessons');
eq(totals('SOURCE SGK seed'),677,'historic SGK');
eq(totals('SOURCE VBT seed'),729,'historic VBT');
eq(totals('Tổng seed 1406'),1406,'historic total');
eq(totals('P3 lịch sử'),707,'P3 archival only');
eq(totals('C1 envelope'),1406,'C1 scaffold');
eq(totals('C1 playable'),0,'C1 no playable');
eq(totals('MASTER SGK'),82,'MASTER SGK');
eq(totals('MASTER VBT'),270,'MASTER VBT');
eq(totals('G2 SGK'),86,'G2 SGK');
eq(totals('G2 VBT'),10,'G2 VBT');
eq(totals('B20 runtime'),51,'legacy B20');
eq(totals('G2B signed'),0,'independent human signoffs');
eq(totals('Renderer grant'),0,'renderer releases');
eq(totals('PublicVariant grant'),0,'student releases');
eq(totals('Owner conflict'),65,'BQA mismatch');
eq(d.risks.historicSourceExcluded,1406,'source pending B');
eq(d.risks.sourceVerifiedV8,0,'V8 source QA pending');
eq(d.risks.c1FullPromptMissing,1053,'source text missing');
eq(d.risks.c1PartialHintOnly,353,'partial prompts');
let tiers={};
for(let i=0;i<75;i++){
 const r=a[i];const c=r.core;
 eq(r.lessonId,'MATH_B'+String(i+1).padStart(3,'0'),'canonical order');
 eq(r.evidence.lessonId,r.lessonId,'evidence matching');
 eq(c['Tổng seed 1406'],c['SOURCE SGK seed']+c['SOURCE VBT seed'],'hist by source');
 eq(c['C1 envelope'],c['Tổng seed 1406'],'C1 by lesson');
 eq(c['C1 playable'],0,'C1 not executable');
 eq(c['Release gate'],'NO_GO','release must fail closed');
 eq(c['Renderer grant'],0,'renderer not approved');
 eq(c['PublicVariant grant'],0,'no approved variant');
 assert.ok(c['SOURCE SGK seed']>0&&c['SOURCE VBT seed']>0,'both historic tracks');
 const n=i+1;
 if(n>24){eq(c['MASTER SGK'],0,'no MASTER SGK detail beyond B024');eq(c['MASTER VBT'],0,'no MASTER VBT detail beyond B024');}
 if(n===20)eq(c['B20 runtime'],51,'B20 legacy only');
 else eq(c['B20 runtime'],0,'only B20 runtime');
 if(n===61)eq(c['Owner conflict'],28,'B061 owner mismatch');
 else if(n===62)eq(c['Owner conflict'],37,'B062 owner mismatch');
 else eq(c['Owner conflict'],0,'other BQA owner matches');
 tiers[c['Coverage tier']]=(tiers[c['Coverage tier']]||0)+1;
}
eq(tiers.MASTER_G2_CANDIDATES,7,'G2 lesson subset');
eq(tiers.MASTER_LEDGER_ONLY,17,'other MASTER lessons');
eq(tiers.HISTORICAL_C1_ONLY,51,'historical-only group');
const scan=JSON.stringify(d).toLowerCase();
for(const key of ['"answer":','"solutionprompt":','"puzzle.ans":','"studentid":','"parentemail":'])assert.ok(!scan.includes(key),'private field in metadata: '+key);
assert.equal(d.noStudentData,true,'no student data');
console.log('COVERAGE75 VALIDATION PASS: 75 lessons; 1406 historic source candidates; 1406 C1 scaffolds; 0 approved/renderable; 65 owner mismatches.');
